import { setSmokeLanguage } from './smoke-language.mjs';
import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { createDemo } from './dockyard.mjs';

await fs.mkdir(path.resolve('.local'), { recursive: true });
const root = await fs.mkdtemp(path.resolve('.local/layout-check-'));
const dataDir = path.join(root, 'data');
await createDemo(dataDir);
await setSmokeLanguage(dataDir);
const artifacts = path.resolve('output/playwright');
await fs.mkdir(artifacts, { recursive: true });
const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE;
let app;
const errors = [];
try {
  app = await electron.launch({ args: [path.resolve('apps/desktop'), '--data-dir', dataDir], env });
  const page = await app.firstWindow();
  page.setDefaultTimeout(15000);
  page.on('pageerror', error => errors.push(error.message));
  await page.waitForFunction(() => !document.querySelector('.workspace-trigger')?.disabled);
  const toggle = page.getByRole('switch', { name: '显示工具标签' });
  await page.waitForFunction(() => innerHeight === 62 && innerWidth === 711);
  assert.equal(await toggle.getAttribute('aria-checked'), 'false');
  await page.screenshot({ path: path.join(artifacts, 'layout-toolbar.png'), omitBackground:true });
  await toggle.click();
  await page.waitForFunction(() => innerHeight === 94);
  assert.equal(await page.locator('.tool-label').first().isVisible(), true);
  await page.reload();
  await page.waitForFunction(() => !document.querySelector('.workspace-trigger')?.disabled && innerHeight === 94);
  assert.equal(await toggle.getAttribute('aria-checked'), 'true');
  await page.screenshot({ path:path.join(artifacts,'layout-labels.png'), omitBackground:true });
  await toggle.click();
  await page.getByRole('button', { name:'更多', exact:true }).click();
  await page.getByRole('button', { name:'我的资源', exact:true }).click();
  await page.waitForFunction(() => innerWidth === 736);
  assert.equal(await page.locator('.filter').evaluate(el => Math.abs(el.getBoundingClientRect().width - el.closest('.popover').clientWidth + 40) < 3), true);
  assert.match(await page.locator('.resource-workspace').textContent(), /勾选加入当前工作区/);
  await page.getByRole('checkbox', { name:'选择 FX Design Rules', exact:true }).uncheck();
  await page.waitForFunction(async () => { const r=await window.dockyard.state();return r.ok && !r.value.workspaces.find(w=>w.id===r.value.activeWorkspaceId).componentIds.includes('fx-rules'); });
  await page.getByRole('checkbox', { name:'选择 FX Design Rules', exact:true }).check();
  await page.waitForFunction(async () => { const r=await window.dockyard.state();return r.ok && r.value.workspaces.find(w=>w.id===r.value.activeWorkspaceId).componentIds.includes('fx-rules'); });
  const dismiss = page.getByRole('button', { name:'关闭提示', exact:true });
  if(await dismiss.count()) await dismiss.click();
  await page.screenshot({ path:path.join(artifacts,'layout-resources.png'), omitBackground:true });
  await page.getByRole('button', { name:'当前色与色盘', exact:true }).click();
  const panel = page.getByRole('region', {name:'颜色面板',exact:true});
  await panel.waitFor();
  const geometry = await panel.evaluate(el => {
    const list=el.querySelector('.design-choice-list'), picker=el.querySelector('.color-picker');
    const rect=n=>n.getBoundingClientRect();
    return { columns:getComputedStyle(list).gridTemplateColumns.split(' ').length, ordered:rect(list).bottom<=rect(picker).top, noWebPreview:!el.querySelector('.design-preview'),
      footerVisible:rect(el.querySelector('.color-panel-footer')).bottom<=innerHeight, overflow:el.scrollWidth>el.clientWidth };
  });
  assert.deepEqual(geometry,{columns:3,ordered:true,noWebPreview:true,footerVisible:true,overflow:false});
  await page.screenshot({ path:path.join(artifacts,'layout-color-top.png'), omitBackground:true });
  await page.getByRole('button',{name:'预览色彩组合：海岸蓝',exact:true}).click();
  assert.match(await panel.locator('.scheme-pick-heading').textContent(), /海岸蓝/);
  const enable=page.getByRole('checkbox',{name:'启用 海岸蓝',exact:true});
  await enable.uncheck();
  await page.waitForFunction(()=>!document.querySelector('[aria-label="启用 海岸蓝"]').checked);
  await enable.check();
  await page.waitForFunction(()=>document.querySelector('[aria-label="启用 海岸蓝"]').checked);
  await page.getByRole('button',{name:'预览色彩组合：海岸蓝',exact:true}).dblclick();
  await page.waitForFunction(()=>document.querySelector('.design-current')?.textContent.includes('海岸蓝'));
  if(await dismiss.count()) await dismiss.click();
  await page.getByLabel('当前色 HEX',{exact:true}).fill('#123456');
  await page.getByLabel('保存颜色名称').fill('布局验收颜色');
  await page.getByRole('button',{name:'保存到色板',exact:true}).click();
  await page.getByText('颜色已保存到色板',{exact:false}).waitFor();
  if(await dismiss.count()) await dismiss.click();
  await page.screenshot({path:path.join(artifacts,'layout-color-save.png'),omitBackground:true});
  await page.keyboard.press('Escape');
  await page.waitForFunction(()=>innerHeight===62&&innerWidth===711);
  await page.getByRole('button',{name:'字体',exact:true}).click();
  await page.getByRole('region',{name:'字体面板',exact:true}).waitFor();
  assert.equal(await page.locator('.popover').evaluate(el=>el.scrollWidth<=el.clientWidth),true);
  await page.screenshot({path:path.join(artifacts,'layout-fonts.png'),omitBackground:true});
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({passed:true,geometry,checks:['toolbar label preference survives reload','native width and height expand/collapse','workspace membership preserved','three-column palettes and viewport-safe footer','palette preview, enable, apply and save','font panel no horizontal overflow'],artifacts},null,2));
} finally { await app?.close(); }
