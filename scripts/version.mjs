import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const root = fileURLToPath(new URL('../', import.meta.url));
export const manifests = ['package.json', 'packages/shared/package.json', 'packages/core/package.json', 'packages/mcp/package.json', 'apps/desktop/package.json'];
export async function readJson(file) { return JSON.parse(await readFile(path.join(root, file), 'utf8')); }
const generated = version => `// Generated by scripts/version.mjs from the root package.json.\nexport const DOCKYARD_VERSION = '${version}';\n`;
function validateVersion(version) {
  if (!/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-(?:[a-z][a-z0-9-]*|0|[1-9]\d*)(?:\.(?:[a-z][a-z0-9-]*|0|[1-9]\d*))*)?$/.test(version)) {
    throw new Error('Use a version such as 0.1.0 or 0.1.0-beta.1.');
  }
}
export async function checkVersion() {
  const pkg = await readJson('package.json');
  validateVersion(pkg.version);
  const lock = await readJson('package-lock.json');
  const errors = [];
  if (lock.version !== pkg.version) errors.push('package-lock.json version');
  for (const file of manifests) {
    const value = await readJson(file);
    const key = file === 'package.json' ? '' : path.posix.dirname(file);
    if (value.version !== pkg.version || lock.packages[key]?.version !== pkg.version) errors.push(file + ' version');
    for (const [name, version] of Object.entries(value.dependencies ?? {})) {
      if (name.startsWith('@dockyard/') && (version !== pkg.version || lock.packages[key]?.dependencies?.[name] !== version)) errors.push(file + ' dependency ' + name);
    }
  }
  if (await readFile(path.join(root, 'packages/shared/src/version.ts'), 'utf8') !== generated(pkg.version)) errors.push('generated shared version');
  if (errors.length) throw new Error('Version mismatch: ' + errors.join(', ') + '. Run npm run version:set -- <version>.');
  return pkg.version;
}
export async function setVersion(version) {
  validateVersion(version);
  const lock = await readJson('package-lock.json');
  const changes = [];
  for (const file of manifests) {
    const value = await readJson(file);
    value.version = version;
    const key = file === 'package.json' ? '' : path.posix.dirname(file);
    if (!lock.packages[key]) throw new Error('Missing lockfile workspace: ' + file);
    lock.packages[key].version = version;
    for (const name of Object.keys(value.dependencies ?? {})) {
      if (name.startsWith('@dockyard/')) {
        value.dependencies[name] = version;
        lock.packages[key].dependencies[name] = version;
      }
    }
    changes.push([file, value]);
  }
  lock.version = version;
  changes.push(['package-lock.json', lock]);
  for (const [file, value] of changes) await writeFile(path.join(root, file), JSON.stringify(value, null, 2) + '\n', 'utf8');
  await writeFile(path.join(root, 'packages/shared/src/version.ts'), generated(version), 'utf8');
  await checkVersion();
}
if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const args = process.argv.slice(2);
  if (args.length !== 1) throw new Error('Usage: node scripts/version.mjs --check|<version>');
  if (args[0] !== '--check') await setVersion(args[0]);
  console.log('Dockyard version: ' + await checkVersion());
}
