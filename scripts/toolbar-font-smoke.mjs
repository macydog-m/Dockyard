import { setSmokeLanguage } from './smoke-language.mjs';
import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { createDemo } from './dockyard.mjs';
import { ResourceRegistry } from '../packages/core/dist/index.js';
import { smokeClipboard } from './smoke-clipboard.mjs';

await fs.mkdir(path.resolve('.local'), { recursive: true });
const root = await fs.mkdtemp(path.resolve('.local/toolbar-font-check-'));
const dataDir = path.join(root, 'data');
await createDemo(dataDir);
await setSmokeLanguage(dataDir);
const artifacts = path.resolve('output/playwright');
await fs.mkdir(artifacts, { recursive: true });
const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE;
let app;
const errors = [];
try {
  app = await electron.launch({ args: [path.resolve('apps/desktop'), '--data-dir', dataDir], env });
  const page = await app.firstWindow();
  const readClipboard = await smokeClipboard(app);
  page.setDefaultTimeout(15000);
  page.on('pageerror', error => errors.push(error.message));
  const ready = () => page.waitForFunction(() => !document.querySelector('.workspace-trigger')?.disabled);
  const dismiss = async () => { const button = page.getByRole('button', { name: '关闭提示', exact: true }); if (await button.count()) await button.click(); };
  const fits = async () => assert.equal(await page.locator('.dock-bar').evaluate(el => el.scrollWidth <= el.clientWidth && el.lastElementChild.getBoundingClientRect().right <= el.getBoundingClientRect().right), true);
  await ready();
  // Native window dimensions can round by up to 2 DIP at fractional Windows scaling.
  await page.waitForFunction(() => Math.abs(innerWidth - 711) <= 2);
  assert.equal(await page.getByRole('toolbar').evaluate(el => el.querySelector('[aria-label="当前色与色盘"]').previousElementSibling.getAttribute('aria-label')), '字体');
  await fits();
  await page.getByRole('button', { name: '更多', exact: true }).click();
  const before = await page.evaluate(async () => (await window.dockyard.state()).value.workspaces);
  await page.getByRole('switch', { name: '显示记事本', exact: true }).click();
  assert.equal(await page.getByRole('toolbar').getByRole('button', { name: '记事本', exact: true }).count(), 0);
  await page.keyboard.press('Escape');
  await page.waitForFunction(() => Math.abs(innerWidth - 676) <= 2 && Math.abs(innerHeight - 62) <= 2);
  await fits();
  await page.reload(); await ready();
  await page.waitForFunction(() => Math.abs(innerWidth - 676) <= 2);
  assert.equal(await page.getByRole('toolbar').getByRole('button', { name: '记事本', exact: true }).count(), 0);
  await page.getByRole('button', { name: '更多', exact: true }).click();
  for (const name of ['配置', '素材', '文件', '规则', '字体', '颜色', '吸色', '截图']) await page.getByRole('switch', { name: '显示' + name, exact: true }).click();
  assert.equal(await page.getByRole('toolbar').getByRole('button', { name: '配置', exact: true }).count(), 0);
  await page.screenshot({ path: path.join(artifacts, 'toolbar-component-settings.png'), omitBackground: true });
  assert.deepEqual(await page.evaluate(async () => (await window.dockyard.state()).value.workspaces), before, 'visibility never changes workspace resource membership or enable state');
  await page.keyboard.press('Escape');
  await page.waitForFunction(() => Math.abs(innerWidth - 320) <= 2);
  await fits();
  await page.getByRole('switch', { name: '显示工具标签', exact: true }).click();
  await page.waitForFunction(() => Math.abs(innerHeight - 94) <= 2);
  await fits();
  await page.screenshot({ path: path.join(artifacts, 'toolbar-components-hidden.png'), omitBackground: true });
  await page.getByRole('button', { name: '更多', exact: true }).click();
  await page.getByRole('button', { name: '全部显示', exact: true }).click();
  await page.keyboard.press('Escape');
  await page.waitForFunction(() => Math.abs(innerWidth - 711) <= 2);
  await fits();
  await page.getByRole('switch', { name: '显示工具标签', exact: true }).click();
  await page.getByRole('button', { name: '字体', exact: true }).click();
  await page.getByRole('spinbutton', { name: '字号', exact: true }).fill('28');
  await page.getByRole('button', { name: '加粗', exact: true }).click();
  await page.getByLabel('文字颜色', { exact: true }).fill('#1a5276');
  const previewStyle = await page.locator('.design-preview>p').evaluate(el => { const s = getComputedStyle(el); return { size: s.fontSize, color: s.color, weight: s.fontWeight }; });
  assert.deepEqual(previewStyle, { size: '28px', color: 'rgb(26, 82, 118)', weight: '700' });
  await page.getByRole('button', { name: '保存设置', exact: true }).click();
  await page.getByText('字体设置已保存', { exact: true }).waitFor();
  await ready(); await dismiss();
  const registry = new ResourceRegistry(dataDir);
  const font = await registry.get('font-dockyard-yahei::body');
  assert.equal(font.size, 28); assert.equal(font.weight, 700); assert.equal(font.color, '#1A5276');
  await page.getByRole('button', { name: '复制 CSS', exact: true }).click();
  await page.getByText('CSS 已复制', { exact: true }).waitFor();
  assert.match(await readClipboard(), /--font-body-color: #1A5276;/);
  await dismiss();
  await page.screenshot({ path: path.join(artifacts, 'font-icon-controls-dark.png'), omitBackground: true });
  // Copying a changed font saves the resource first, while keeping the AI text concise.
  await page.getByRole('spinbutton', { name: '字号', exact: true }).fill('20');
  await page.getByRole('button', { name: '复制字体指引：Microsoft YaHei', exact: true }).click();
  await page.getByText('字体指引已复制，可粘贴给 AI', { exact: true }).waitFor();
  assert.equal(await readClipboard(), '请使用 Dockyard 中的字体 "Microsoft YaHei"。');
  assert.equal((await new ResourceRegistry(dataDir).get('font-dockyard-yahei::body')).size, 20);
  await dismiss();
  await page.getByRole('button', { name: '加粗', exact: true }).click();
  await page.getByRole('button', { name: '文字颜色跟随配色', exact: true }).click();
  await page.getByRole('button', { name: '保存设置', exact: true }).click();
  await page.getByText('字体设置已保存', { exact: true }).waitFor(); await ready(); await dismiss();
  await page.reload(); await ready();
  await page.getByRole('button', { name: '字体', exact: true }).click();
  assert.equal(await page.getByRole('spinbutton', { name: '字号', exact: true }).inputValue(), '20');
  assert.equal(await page.getByRole('button', { name: '加粗', exact: true }).getAttribute('aria-pressed'), 'false');
  assert.equal((await new ResourceRegistry(dataDir).get('font-dockyard-yahei::body')).color, undefined);
  // Applying an unregistered preset must not overwrite its just-saved changes.
  await page.getByRole('button', { name: '预览字体：Arial', exact: true }).click();
  await page.getByRole('spinbutton', { name: '字号', exact: true }).fill('24');
  await page.getByRole('button', { name: '预览字体：Arial', exact: true }).dblclick();
  await page.waitForFunction(() => document.querySelector('.design-current')?.textContent.includes('Arial'));
  await ready(); await dismiss();
  assert.equal((await new ResourceRegistry(dataDir).get('font-dockyard-arial::body')).size, 24);
  await page.getByRole('spinbutton', { name: '字号', exact: true }).fill('26');
  await page.getByRole('button', { name: '预览字体：Arial', exact: true }).dblclick();
  await page.getByText('字体设置已保存', { exact: true }).waitFor(); await ready(); await dismiss();
  assert.equal((await new ResourceRegistry(dataDir).get('font-dockyard-arial::body')).size, 26);
  await page.getByRole('button', { name: '切换到白天模式', exact: true }).click();
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'light');
  await page.screenshot({ path: path.join(artifacts, 'font-icon-controls-light.png'), omitBackground: true });
  await fits();
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ passed: true, checks: ['font next to color', 'visibility persistence', 'native width and empty groups', 'all-hidden recovery and labels', 'resources unchanged', 'font preview / save / reload / reset', 'CSS and queryable AI resource', 'light and dark'], artifacts }, null, 2));
} finally { await app?.close(); }
